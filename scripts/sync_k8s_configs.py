#!/usr/bin/env python3
"""Regenerate k8s/generated/*.yaml (ConfigMaps) from the files that are the single source of truth.

    python scripts/sync_k8s_configs.py          # rewrite k8s/generated/
    python scripts/sync_k8s_configs.py --check # exit 1 if the generated files are out of date (CI)

Why: `kubectl apply -k k8s/` must be self-contained, but the Postgres init script, the Prometheus
config/alert rules and the Grafana dashboard also have to work with docker-compose. Edit the
originals, then run this script; never edit k8s/generated/ by hand.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "k8s" / "generated"

# output file -> (ConfigMap name, {key in ConfigMap: source file})
CONFIGMAPS = {
    "postgres-init.yaml": (
        "postgres-init",
        {"init-databases.sh": "infra/postgres/init-databases.sh"},
    ),
    "prometheus-config.yaml": (
        "prometheus-config",
        {
            "prometheus.yml": "monitoring/prometheus/prometheus-k8s.yml",
            "alerts.yml": "monitoring/prometheus/alerts.yml",
        },
    ),
    "grafana-provisioning.yaml": (
        "grafana-provisioning",
        {
            "datasource.yml": "monitoring/grafana/provisioning/datasources/prometheus.yml",
            "dashboards.yml": "monitoring/grafana/provisioning/dashboards/dashboards.yml",
        },
    ),
    "grafana-dashboards.yaml": (
        "grafana-dashboards",
        {"cloud-payroll.json": "monitoring/grafana/dashboards/cloud-payroll.json"},
    ),
}


def render(name: str, files: dict[str, str]) -> str:
    lines = [
        "# GENERATED by scripts/sync_k8s_configs.py from the files named below. DO NOT EDIT BY HAND.",
        "apiVersion: v1",
        "kind: ConfigMap",
        "metadata:",
        f"  name: {name}",
        "  labels:",
        "    app.kubernetes.io/part-of: cloud-payroll",
        "data:",
    ]
    for key, source in files.items():
        text = (ROOT / source).read_text()
        if "\t" in text:
            sys.exit(f"{source} contains a tab character, which a YAML block scalar cannot hold")
        if text.splitlines() and text.splitlines()[0][:1] in (" ", ""):
            sys.exit(f"{source}: first line must start in column 0 (YAML block scalar rule)")
        lines.append(f"  # from {source}")
        lines.append(f"  {key}: |")
        # trailing spaces are legal in a literal block but invisible; strip them for stable diffs
        lines.extend(("    " + line).rstrip() if line else "" for line in text.rstrip("\n").split("\n"))
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if k8s/generated is out of date")
    args = ap.parse_args()

    stale = []
    for filename, (name, files) in CONFIGMAPS.items():
        content = render(name, files)
        target = OUT / filename
        if args.check:
            if not target.exists() or target.read_text() != content:
                stale.append(filename)
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
            print(f"wrote {target.relative_to(ROOT)}")
    if args.check:
        if stale:
            print("out of date: " + ", ".join(stale) + "\nrun: python scripts/sync_k8s_configs.py")
            return 1
        print("k8s/generated is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
